#!/usr/bin/env python3
"""Turn a pair of k6 --summary-export JSON files into results.md.

Usage:
    generate_results_md.py \
        --axum benchmark-artifacts/axum-summary.json \
        --bun benchmark-artifacts/bun-summary.json \
        --output results.md \
        --commit <sha> \
        --run-url <workflow run URL>

Only stdlib is used on purpose, since the CI job that calls this script
doesn't otherwise need a Python dependency install step.
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

ENDPOINTS = [
    ("list_items", "GET /items"),
    ("get_item", "GET /items/{id}"),
    ("create_item", "POST /items"),
    ("update_item", "PUT /items/{id}"),
    ("delete_item", "DELETE /items/{id}"),
]

FRAMEWORKS = [
    ("axum", "Axum (Rust)"),
    ("bun", "Bun (TypeScript)"),
]


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--axum", required=True, type=Path, help="axum k6 summary JSON")
    p.add_argument("--bun", required=True, type=Path, help="bun k6 summary JSON")
    p.add_argument("--output", required=True, type=Path, help="path to write results.md")
    p.add_argument("--commit", default="unknown", help="git commit SHA this run was built from")
    p.add_argument("--run-url", default="", help="URL of the CI run that produced this data")
    p.add_argument("--vus", default="50", help="virtual users used in the k6 test")
    p.add_argument("--duration", default="30s", help="duration of the k6 test")
    return p.parse_args()


def load_summary(path: Path) -> dict:
    with path.open() as f:
        return json.load(f)


def metric(summary: dict, name: str) -> dict:
    """Return the `values` dict for a metric, or {} if it's missing.

    Metrics scoped by tag (e.g. "http_req_duration{name:list_items}") only
    show up in the export if a threshold references that exact tag filter
    -- which load-test.js does for every endpoint, so this should always
    resolve. Falling back to {} keeps the report generator from crashing
    if a metric is ever renamed or a threshold is removed upstream.
    """
    return summary.get("metrics", {}).get(name, {}).get("values", {})


def fmt_ms(values: dict, key: str) -> str:
    v = values.get(key)
    return f"{v:.1f}" if isinstance(v, (int, float)) else "n/a"


def fmt_count(values: dict, key: str) -> str:
    v = values.get(key)
    return f"{v:,.0f}" if isinstance(v, (int, float)) else "n/a"


def fmt_pct(values: dict, key: str) -> str:
    v = values.get(key)
    return f"{v * 100:.2f}%" if isinstance(v, (int, float)) else "n/a"


def overall_row(label: str, summary: dict) -> str:
    reqs = metric(summary, "http_reqs")
    dur = metric(summary, "http_req_duration")
    failed = metric(summary, "http_req_failed")
    checks = metric(summary, "checks")

    return (
        f"| {label} "
        f"| {fmt_count(reqs, 'count')} "
        f"| {fmt_count(reqs, 'rate')}/s "
        f"| {fmt_pct(failed, 'rate')} "
        f"| {fmt_pct(checks, 'rate')} "
        f"| {fmt_ms(dur, 'avg')} "
        f"| {fmt_ms(dur, 'p(95)')} "
        f"| {fmt_ms(dur, 'p(99)')} |"
    )


def endpoint_table(summaries: dict) -> list[str]:
    header = ["| Endpoint | " + " | ".join(l for _, l in FRAMEWORKS) + " |"]
    header.append("|---" * (len(FRAMEWORKS) + 1) + "|")
    rows = [header[0], header[1]]

    for tag, display in ENDPOINTS:
        cells = [display]
        for key, _ in FRAMEWORKS:
            values = metric(summaries[key], f"http_req_duration{{name:{tag}}}")
            cells.append(fmt_ms(values, "p(95)"))
        rows.append("| " + " | ".join(cells) + " |")

    return rows


def raw_block(label: str, path: Path) -> list[str]:
    text = path.read_text() if path.exists() else "(stdout not captured)"
    return [
        "<details>",
        f"<summary>{label} — raw k6 output</summary>",
        "",
        "```",
        text.strip(),
        "```",
        "",
        "</details>",
    ]


def main() -> None:
    args = parse_args()

    summaries = {
        "axum": load_summary(args.axum),
        "bun": load_summary(args.bun),
    }

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    run_line = f" — [workflow run]({args.run_url})" if args.run_url else ""

    lines: list[str] = []
    lines.append("# Benchmark Results")
    lines.append("")
    lines.append(
        f"_Last updated: {now} — commit `{args.commit[:12]}`{run_line}_"
    )
    lines.append("")
    lines.append(
        "Automatically generated by `.github/workflows/benchmark.yml`. "
        "Do not edit this file by hand — it's overwritten on every scheduled "
        "run. See [`scripts/generate_results_md.py`](scripts/generate_results_md.py) "
        "if you want to change the report format."
    )
    lines.append("")

    lines.append("## Methodology")
    lines.append("")
    lines.append(
        f"- Load generator: [k6](https://k6.io), {args.vus} virtual users for "
        f"{args.duration}, one full CRUD cycle (list → create → get → update → "
        "delete) per iteration."
    )
    lines.append(
        "- Both services run in Docker via their own `docker-compose.yml`, "
        "each **capped to exactly 1 CPU core** (`cpus: \"1.0\"`); Postgres "
        "runs unconstrained in both, so it's never the bottleneck."
    )
    lines.append(
        "- The two services are benchmarked sequentially, never "
        "concurrently, so each gets the CI runner to itself."
    )
    lines.append(
        "- Both apps expose an identical schema and identical endpoints — "
        "see [`axum-item-crud/README.md`](axum-item-crud/README.md) and "
        "[`bun-item-crud/README.md`](bun-item-crud/README.md) for details."
    )
    lines.append(
        "- Numbers below come from a single CI run and will vary between "
        "runs — GitHub-hosted runners are shared, general-purpose VMs, not "
        "dedicated benchmarking hardware. Treat this as a directional "
        "comparison, not a lab-grade result."
    )
    lines.append("")

    lines.append("## Summary")
    lines.append("")
    lines.append(
        "| Framework | Requests | Req/s | Failed | Checks passed | Avg (ms) | p95 (ms) | p99 (ms) |"
    )
    lines.append("|---|---|---|---|---|---|---|---|")
    for key, label in FRAMEWORKS:
        lines.append(overall_row(label, summaries[key]))
    lines.append("")

    lines.append("## Per-endpoint latency (p95, ms)")
    lines.append("")
    lines.extend(endpoint_table(summaries))
    lines.append("")

    lines.append("## Raw k6 output")
    lines.append("")
    for key, label in FRAMEWORKS:
        stdout_path = args.axum.parent / f"{key}-stdout.txt"
        lines.extend(raw_block(label, stdout_path))
        lines.append("")

    args.output.write_text("\n".join(lines).rstrip() + "\n")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
